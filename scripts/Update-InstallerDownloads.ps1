    @("en/en_US/libritts_r/medium", "en_US-libritts_r-medium"))

function Get-Sha256OfUrl([string] $url) {
    $file = Join-Path ([System.IO.Path]::GetTempPath()) ([guid]::NewGuid().ToString("N"))
    try {
        Invoke-WebRequest -Uri $url -OutFile $file -UseBasicParsing
        return (Get-FileHash -LiteralPath $file -Algorithm SHA256).Hash.ToLowerInvariant()
    }
    finally {
        Remove-Item -LiteralPath $file -Force -ErrorAction SilentlyContinue
    }
}

function Get-HuggingFaceTree([string] $repository, [string] $path) {
    $address = "https://huggingface.co/api/models/$repository/tree/main"
    if ($path) { $address += "/$path" }
    return Invoke-RestMethod -Uri $address
}

# Invoke-RestMethod may hand back a JSON array as one object: look through both levels.
function Find-TreeEntry($tree, [string] $path) {
    foreach ($level in @($tree)) {
        foreach ($entry in @($level)) {
            if ($entry.path -eq $path) { return $entry }
        }
    }

    return $null
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("// Generated by scripts\Update-InstallerDownloads.ps1. Do not edit by hand.")
$lines.Add("// Third-party files fetched at install time: address, file name, SHA-256, target under local-voice.")
$lines.Add("")
$lines.Add("procedure AddLocalVoiceDownloads;")
$lines.Add("begin")

# Piper and whisper.cpp are zips: the SHA-256 is of the archive, extracted after the download.
Write-Host "Piper..."
$piperHash = Get-Sha256OfUrl $piperUrl
$lines.Add("  AddDownload('$piperUrl', 'piper.zip', '$piperHash', '');")

Write-Host "whisper.cpp..."
$whisperHash = Get-Sha256OfUrl $whisperUrl
$lines.Add("  AddDownload('$whisperUrl', 'whisper.zip', '$whisperHash', '');")

Write-Host "Whisper model..."
$model = Find-TreeEntry (Get-HuggingFaceTree "ggerganov/whisper.cpp" "") $modelName
if (-not $model -or -not $model.PSObject.Properties["lfs"]) { throw "The Whisper model $modelName was not found on Hugging Face." }
$lines.Add("  AddDownload('https://huggingface.co/ggerganov/whisper.cpp/resolve/main/$modelName', '$modelName', '$($model.lfs.oid)', 'models\$modelName');")

foreach ($voice in $voices) {
    $folder = $voice[0]
    $name = $voice[1]
    Write-Host "Voice $name..."
    $tree = Get-HuggingFaceTree "rhasspy/piper-voices" $folder
    $onnx = Find-TreeEntry $tree "$folder/$name.onnx"
    if (-not $onnx -or -not $onnx.PSObject.Properties["lfs"]) { throw "The voice $name was not found on Hugging Face." }

    $base = "https://huggingface.co/rhasspy/piper-voices/resolve/main/$folder/$name"
    $jsonHash = Get-Sha256OfUrl "$base.onnx.json"
    $lines.Add("  AddDownload('$base.onnx', '$name.onnx', '$($onnx.lfs.oid)', 'voices\$name.onnx');")
    $lines.Add("  AddDownload('$base.onnx.json', '$name.onnx.json', '$jsonHash', 'voices\$name.onnx.json');")
}

$lines.Add("end;")
[System.IO.File]::WriteAllText($output, ($lines -join "`r`n") + "`r`n", (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $output ($($lines.Count) lines)."
