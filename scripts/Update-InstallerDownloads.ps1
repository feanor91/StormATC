# Writes installer\downloads.inc.iss: the list of third-party files the installer downloads for
# the local voice (Piper, whisper.cpp, a Whisper model and the controller voices), each pinned
# to an address and a SHA-256 so that a changed or corrupted download is refused.
#
# StormATC does not redistribute these files: the installer fetches them from their publishers
# (GitHub and Hugging Face). Edit the lists below, run this script, and commit the result.

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$repositoryRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot ".."))
$output = Join-Path $repositoryRoot "installer\downloads.inc.iss"

$piperUrl = "https://github.com/rhasspy/piper/releases/download/2023.11.14-2/piper_windows_amd64.zip"
$whisperUrl = "https://github.com/ggml-org/whisper.cpp/releases/download/b5454/whisper-bin-x64.zip"
$modelName = "ggml-small-q5_1.bin"

# Voices: Hugging Face folder inside rhasspy/piper-voices, then the voice name.
$voices = @(
    @("fr/fr_FR/siwis/medium", "fr_FR-siwis-medium"),
    @("fr/fr_FR/tom/medium", "fr_FR-tom-medium"),
    @("fr/fr_FR/upmc/medium", "fr_FR-upmc-medium"),
    @("fr/fr_FR/mls/medium", "fr_FR-mls-medium"),
    @("en/en_GB/alan/medium", "en_GB-alan-medium"),
    @("en/en_GB/alba/medium", "en_GB-alba-medium"),
    @("en/en_GB/cori/medium", "en_GB-cori-medium"),
    @("en/en_GB/jenny_dioco/medium", "en_GB-jenny_dioco-medium"),
    @("en/en_GB/northern_english_male/medium", "en_GB-northern_english_male-medium"),
    @("en/en_GB/vctk/medium", "en_GB-vctk-medium"),
    @("en/en_US/amy/medium", "en_US-amy-medium"),
    @("en/en_US/hfc_female/medium", "en_US-hfc_female-medium"),
    @("en/en_US/hfc_male/medium", "en_US-hfc_male-medium"),
