[CmdletBinding()]
param()

# Builds the Flow Pro (Parallel 42) version of the StormATC panel from the shared sources in
# msfs-panel\web. Flow Pro widgets are three snippets (HTML, CSS, JS) pasted into its Custom
# Script editor, so there is nothing to compile: the files are written to msfs-panel\flowpro
# and committed, ready to copy.

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

$repositoryRoot = [System.IO.Path]::GetFullPath((Join-Path $PSScriptRoot ".."))
$web = Join-Path $repositoryRoot "msfs-panel\web"
$output = Join-Path $repositoryRoot "msfs-panel\flowpro"
New-Item -ItemType Directory -Force $output | Out-Null

$utf8 = New-Object System.Text.UTF8Encoding($false)
$core = [System.IO.File]::ReadAllText((Join-Path $web "panel-core.js"), $utf8)
$css = [System.IO.File]::ReadAllText((Join-Path $web "panel.css"), $utf8)

$html = @'
<div id="StormAtcRoot"></div>
'@

# Flow calls html_created() once the widget's HTML exists, and run() when it is shown.
$entry = @'


// --- Flow Pro life cycle ---------------------------------------------------------------

var stormAtcPanel = null;

function html_created() {
  stormAtcPanel = StormAtcPanel.mount(document.getElementById('StormAtcRoot'));
}

function run() {
  // The panel keeps itself up to date; nothing to do when the widget is shown.
}
'@

$header = "// Generated by scripts/Build-FlowProWidget.ps1 from msfs-panel/web/panel-core.js. Do not edit here.`n"
$cssHeader = "/* Generated by scripts/Build-FlowProWidget.ps1 from msfs-panel/web/panel.css. Do not edit here. */`n"

[System.IO.File]::WriteAllText((Join-Path $output "code.html"), $html + "`n", $utf8)
[System.IO.File]::WriteAllText((Join-Path $output "code.css"), $cssHeader + $css, $utf8)
[System.IO.File]::WriteAllText((Join-Path $output "code.js"), $header + $core.TrimEnd() + "`n" + $entry, $utf8)

Write-Host "Flow Pro widget written to $output"
